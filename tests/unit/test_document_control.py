class FakeClient:
    def __init__(self, root=ROOT, missing_tasks=(), acceptance_error=None):
        self.root = root
        self.missing = set(missing_tasks)
        self.acceptance_error = acceptance_error
        self.calls = []
        self.counts = []

    def get_one(self, path):
        self.calls.append(("get_one", path))
        task_id = int(path.split("(")[1].split(")")[0])
        if task_id in self.missing:
            raise DirectumError("Запись не существует", status_code=400)
        return dict(self.root, Id=task_id)

    def query(self, entity_set, **kw):
        self.calls.append((entity_set, kw))
        f = kw.get("filter_", "")
        if entity_set == "IActionItemExecutionTasks":
            if f.startswith("MainTaskId"):
                return TREE
            return [task(1), task(2, deadline=None, HasIndefiniteDeadline=True)]
        if entity_set == "IActionItemExecutionAssignments":
            if f.startswith("Id eq"):
                return [{"Id": 3609, "Task": {"Id": 100}}]
            return ASSIGNMENTS
        if entity_set == "IDeadlineExtensionTasks":
            return EXTENSIONS
        if entity_set == "IDeadlineExtensionAssignments":
            return [{"Id": 1, "Task": {"Id": 900}, "Result": "Accept", "Completed": "2026-09-11T09:00:00+04:00"},
                    {"Id": 2, "Task": {"Id": 902}, "Result": "Decline", "Completed": None}]
        if entity_set == "IActionItemSupervisorAssignments":
            if self.acceptance_error:
                raise self.acceptance_error
            return [{"Id": 50, "Task": {"Id": 102}, "Status": "Completed", "Result": "Agree", "Performer": {"Name": "Контролёр К. К."},
                     "Created": "2026-09-24T10:00:00+04:00", "Completed": "2026-09-25T10:00:00+04:00", "Deadline": None}]
        if entity_set == "IStatusReportRequestTasks":
            return [
                {"Id": 700, "Status": "InProcess", "Created": "2026-09-24T10:00:00+04:00", "Started": "2026-09-24T10:05:00+04:00",
                 "MaxDeadline": "2026-09-26T00:00:00+04:00", "Report": None, "ReportNote": None,
                 "Assignee": {"Name": "Сидоров С. С."}, "Author": {"Name": "Контролёр К. К."}, "ParentTask": {"Id": 101}},
                {"Id": 701, "Status": "Completed", "Created": "2026-09-10T10:00:00+04:00", "Started": None,
                 "MaxDeadline": "2026-09-12T00:00:00+04:00", "Report": "Работа идёт, сдадим в срок.", "ReportNote": None,
                 "Assignee": {"Name": "Иванов И. И."}, "Author": {"Name": "Руководитель Р. Р."}, "ParentTask": {"Id": 100}},
                {"Id": 702, "Status": "InProcess", "Created": "2026-09-10T10:00:00+04:00", "MaxDeadline": None,
                 "Assignee": {"Name": "X"}, "Author": {"Name": "Y"}, "ParentTask": {"Id": 77}},
            ]
        if entity_set == "ISimpleTasks":
            if "по поручению № 101:" in kw.get("filter_", ""):
                return [{"Id": 800, "Subject": "Запрос отчета по поручению № 101: Поручение 101", "Status": "Completed",
                         "Created": "2026-09-20T10:00:00+04:00", "Started": "2026-09-20T10:01:00+04:00",
                         "MaxDeadline": "2026-09-22T00:00:00+04:00", "Author": {"Name": "Контролёр К. К."}}]
            return []
        if entity_set == "IAssignments":
            return [{"Id": 1, "Status": "Completed", "Task": {"Id": 800}, "Performer": {"Name": "Сидоров С. С."},
                     "Texts": [{"Body": "Выполнено на 80 %.", "Created": "2026-09-21T10:00:00+04:00", "IsAutoGenerated": False},
                               {"Body": "авто", "Created": "2026-09-21T11:00:00+04:00", "IsAutoGenerated": True}]}]
        if entity_set == "IOfficialDocuments":
            return [{"Id": 500, "Name": "Вх. письмо"}, {"Id": 501, "Name": "Приложение"}]
        raise AssertionError(entity_set)

